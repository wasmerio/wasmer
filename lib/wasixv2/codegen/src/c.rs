/// Internal musl headers, included for the `@c` types and constants they define
/// (`FUTEX_*`, `IPC_64`).
const INTERNAL_HEADERS: &[&str] = &["futex.h", "ksigaction.h", "syscall.h"];

pub struct GeneratedFile {
    /// Path relative to the libc2 root.
    pub path: &'static str,
    pub contents: String,
}

/// Generates the four libc2 files, in a fixed order.
pub fn generate(model: &Model) -> Result<Vec<GeneratedFile>> {
    if model.target != Target::WASM32 {
        bail!("the C backend only supports wasm32 (musl splits 64-bit args into two longs)");
    }
    let syscalls = syscalls(model)?;
    Ok(vec![
        GeneratedFile {
            path: SYSCALL_NUMBERS_PATH,
            contents: syscall_numbers(&syscalls),
        },
        GeneratedFile {
            path: SYSCALLS_HEADER_PATH,
            contents: syscalls_header(&syscalls),
        },
        GeneratedFile {
            path: DYN_PATH,
            contents: dyn_switch(&syscalls),
        },
        GeneratedFile {
            path: ASSERTS_PATH,
            contents: asserts(model)?,
        },
    ])
}

/// C type of an import param or result: a pure function of the WIT type (never `@c`), so the
/// wasm signature follows from the WIT alone.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum CType {
    Int,
    UInt,
    Long,
    ULong,
    LongLong,
    ULongLong,
    Ptr,
    ConstPtr,
}

impl CType {
    fn spelling(self) -> &'static str {
        match self {
            CType::Int => "int",
            CType::UInt => "unsigned int",
            CType::Long => "long",
            CType::ULong => "unsigned long",
            CType::LongLong => "long long",
            CType::ULongLong => "unsigned long long",
            CType::Ptr => "void *",
            CType::ConstPtr => "const void *",
        }
    }

    /// musl argument slots param `p` of `f` occupies: two for a 64-bit value, unless it is
    /// `@c-one-slot`.
    fn slots(self, f: &Function, p: &Param) -> usize {
        match self {
            CType::LongLong | CType::ULongLong if !f.c_one_slot.contains(&p.name) => 2,
            _ => 1,
        }
    }

    fn of_prim(p: Prim) -> CType {
        match p {
            Prim::S8 | Prim::S16 | Prim::S32 => CType::Int,
            Prim::U8 | Prim::U16 | Prim::U32 => CType::UInt,
            Prim::S64 => CType::LongLong,
            Prim::U64 => CType::ULongLong,
        }
    }

    /// `ty` must be a validated scalar.
    fn of(model: &Model, ty: &TyRef) -> CType {
        let name = match ty {
            TyRef::Prim(p) => return CType::of_prim(*p),
            TyRef::Named(n) => n,
            TyRef::Array(..) => unreachable!("params and results are validated scalars"),
        };
        let def = model.type_def(name).expect("validated reference");
        match &def.kind {
            TypeKind::Pointer(p) if p.mutable => CType::Ptr,
            TypeKind::Pointer(_) => CType::ConstPtr,
            TypeKind::Alias(a) if a.pointer_sized => match model.scalar_prim(&a.target) {
                Some(p) if p.is_signed() => CType::Long,
                _ => CType::ULong,
            },
            TypeKind::Alias(a) => CType::of(model, &a.target),
            TypeKind::Constants(c) => CType::of_prim(c.repr),
            TypeKind::Record(_) => unreachable!("params and results are validated scalars"),
        }
    }
}

struct Syscall<'a> {
    f: &'a Function,
    module: &'a str,
    nr: u32,
    /// musl's spelling: `__NR_<sys_name>`.
    sys_name: &'a str,
    params: Vec<(&'a Param, CType)>,
    result: Option<CType>,
}

/// Functions of the [`SYSCALL_MODULE`] interfaces with `@nr`, ascending by number. Extensions
/// (no `@nr`) are not reachable through musl's `__syscallN`, so libc2 declares them by hand.
fn syscalls(model: &Model) -> Result<Vec<Syscall<'_>>> {
    let mut out = Vec::new();
    for iface in &model.interfaces {
        let Some(module) = iface.module.as_deref() else {
            continue;
        };
        if module != SYSCALL_MODULE {
            continue;
        }
        for f in &iface.functions {
            let Some(nr) = f.nr else {
                continue;
            };
            let params: Vec<_> = f
                .params
                .iter()
                .map(|p| (p, CType::of(model, &p.ty)))
                .collect();
            let slots: usize = params.iter().map(|(p, t)| t.slots(f, p)).sum();
            if slots > MAX_SLOTS {
                bail!(
                    "function `{}` needs {slots} musl argument slots (64-bit params take two \
                     unless `@c-one-slot`), more than the {MAX_SLOTS} musl passes",
                    f.name
                );
            }
            out.push(Syscall {
                f,
                module,
                nr,
                sys_name: f.sys_name.as_deref().unwrap_or(&f.import_name),
                params,
                result: f.result.as_ref().map(|r| CType::of(model, r)),
            });
        }
    }
    out.sort_by_key(|s| s.nr);
    let mut seen = HashMap::new();
    for s in &out {
        if let Some(prev) = seen.insert(s.sys_name, &s.f.name) {
            bail!(
                "functions `{prev}` and `{}` both map to `__NR_{}`",
                s.f.name,
                s.sys_name
            );
        }
    }
    Ok(out)
}

/// `bits/syscall.h.in`: copied verbatim into `<bits/syscall.h>` and post-processed by musl's
/// `sed`, so it holds nothing but `#define` lines (no generated-file header).
fn syscall_numbers(syscalls: &[Syscall<'_>]) -> String {
    let mut out = String::new();
    for s in syscalls {
        let _ = writeln!(out, "#define __NR_{}\t{}", s.sys_name, s.nr);
    }
    for (alias, target) in NR_ALIASES {
        let defined = |n: &str| syscalls.iter().any(|s| s.sys_name == n);
        if defined(target) && !defined(alias) {
            let _ = writeln!(out, "#define __NR_{alias}\t__NR_{target}");
        }
    }
    out
}

fn syscalls_header(syscalls: &[Syscall<'_>]) -> String {
    let mut out = String::from(HEADER);
    out.push_str(&SYSCALLS_PREAMBLE.replace("$COUNT", &syscalls.len().to_string()));
    for s in syscalls {
        out.push_str(&declaration(s));
    }
    out.push_str(ARMS_COMMENT);
    for s in syscalls {
        out.push_str(&arm(s));
    }
    out.push_str("\n#endif\n");
    out
}

/// Prototypes carry no parameter names: a macro of the including TU could clash with them.
fn declaration(s: &Syscall<'_>) -> String {
    let import = &s.f.import_name;
    let sig = s
        .params
        .iter()
        .map(|(p, t)| {
            let ty = t.spelling();
            let sep = if ty.ends_with('*') { "" } else { " " };
            format!("{ty}{sep}{}", names::snake(&p.name))
        })
        .collect::<Vec<_>>()
        .join(", ");
    let proto = if s.params.is_empty() {
        "void".to_string()
    } else {
        let types: Vec<_> = s.params.iter().map(|(_, t)| t.spelling()).collect();
        types.join(", ")
    };
    let noreturn = if s.f.noreturn {
        " __attribute__((__noreturn__))"
    } else {
        ""
    };
    let ret = s.result.map_or("void", CType::spelling);
    format!(
        "/* {nr}: {import}({sig}) */\n\
         __attribute__((__import_module__(\"{module}\"), __import_name__(\"{import}\"))){noreturn}\n\
         {ret} __wasix2_{import}({proto});\n",
        nr = s.nr,
        module = s.module,
    )
}

fn arm(s: &Syscall<'_>) -> String {
    let mut slot = 0;
    let mut exprs = Vec::new();
    for (p, t) in &s.params {
        let ty = t.spelling();
        exprs.push(match t {
            CType::Ptr | CType::ConstPtr => format!("({ty})(__UINTPTR_TYPE__)(a{slot})"),
            CType::LongLong | CType::ULongLong if t.slots(s.f, p) == 1 => {
                format!("({ty})(a{slot})")
            }
            CType::LongLong | CType::ULongLong => {
                let (lo, hi) = match s.f.split_order(&p.name) {
                    SplitOrder::LoHi => (slot, slot + 1),
                    SplitOrder::HiLo => (slot + 1, slot),
                };
                format!("({ty})__wx2_ll(a{lo}, a{hi})")
            }
            _ => format!("({ty})(a{slot})"),
        });
        slot += t.slots(s.f, p);
    }
    let mut slots: Vec<String> = (0..slot).map(|i| format!("a{i}")).collect();
    slots.push("...".to_string());
    let call = format!("__wasix2_{}({})", s.f.import_name, exprs.join(", "));
    // Arms are used as `long` expressions (e.g. `return` in __syscall_dyn).
    let call = match s.result {
        Some(_) => call,
        None => format!("({call}, 0L)"),
    };
    let nr = s.nr;
    format!(
        "#define __wx2_nr_{nr}(...) __wx2_a_{nr}(__VA_ARGS__, 0, 0, 0, 0, 0, 0)\n\
         #define __wx2_a_{nr}({}) {call}\n",
        slots.join(", ")
    )
}

fn dyn_switch(syscalls: &[Syscall<'_>]) -> String {
    let mut out = String::from(HEADER);
    out.push_str(DYN_PREAMBLE);
    for s in syscalls {
        let _ = writeln!(
            out,
            "\tcase {nr}: return __wx2_nr_{nr}(a, b, c, d, e, f);",
            nr = s.nr
        );
    }
    out.push_str("\tdefault: return -ENOSYS;\n\t}\n}\n");
    out
}

fn asserts(model: &Model) -> Result<String> {
    let mut out = String::from(HEADER);
    out.push_str(ASSERTS_PREAMBLE_HEAD);
    for h in ASSERT_HEADERS {
        let _ = writeln!(out, "#include <{h}>");
    }
    for h in INTERNAL_HEADERS {
        let _ = writeln!(out, "#include \"{h}\"");
    }
    out.push_str(ASSERTS_MACROS);
    out.push_str(&layout_asserts(model)?);
    out.push_str(KSIGACTION_CHECK);
    out.push_str(&const_asserts(model)?);
    Ok(out)
}

/// Every type with `@c` (except `@kernel-only` records): scalars as one block, then each record
/// with its member offsets.
fn layout_asserts(model: &Model) -> Result<String> {
    let mut seen: HashMap<&str, &TypeDef> = HashMap::new();
    let (mut scalars, mut records) = (String::new(), String::new());
    for t in &model.types {
        let Some(c) = t.c_type.as_deref() else {
            continue;
        };
        if matches!(&t.kind, TypeKind::Record(r) if r.kernel_only) {
            continue;
        }
        let is_record = |t: &TypeDef| matches!(t.kind, TypeKind::Record(_));
        if let Some(prev) = seen.get(c) {
            // `@c(int)` on several aliases is fine; two definitions of one struct are not.
            if prev.layout != t.layout || is_record(prev) || is_record(t) {
                bail!(
                    "types `{}` and `{}` both claim C type `{c}`",
                    prev.name,
                    t.name
                );
            }
            continue;
        }
        seen.insert(c, t);
        let layout = format!(
            "__WX2_LAYOUT({c}, {}, {});\n",
            t.layout.size, t.layout.align
        );
        let TypeKind::Record(r) = &t.kind else {
            scalars.push_str(&layout);
            continue;
        };
        records.push('\n');
        records.push_str(&layout);
        for f in r.fields.iter().filter(|f| !f.c_skip) {
            let member = f.c_name.clone().unwrap_or_else(|| names::snake(&f.name));
            let _ = writeln!(records, "__WX2_OFFSET({c}, {member}, {});", f.offset);
        }
    }
    if !scalars.is_empty() {
        scalars.insert(0, '\n');
    }
    Ok(scalars + &records)
}

/// Every enum/flags member, guarded by `#ifdef` since musl lacks some Linux constants
/// (`@c-enum` families are C enumerators, invisible to `#ifdef`, so they are asserted unguarded).
fn const_asserts(model: &Model) -> Result<String> {
    let mut out = String::new();
    let mut values: BTreeMap<&str, (i128, &str)> = BTreeMap::new();
    for t in &model.types {
        let TypeKind::Constants(c) = &t.kind else {
            continue;
        };
        let mut family = String::new();
        for m in &c.members {
            if m.c_skip {
                continue;
            }
            match values.get(m.c_name.as_str()) {
                Some((v, _)) if *v == m.value => continue,
                Some((v, prev)) => bail!(
                    "constant `{}` is {v} in `{prev}` but {} in `{}`",
                    m.c_name,
                    m.value,
                    t.name
                ),
                None => {}
            }
            values.insert(&m.c_name, (m.value, &t.name));
            let assert = format!("__WX2_CONST({}, {});\n", m.c_name, c_literal(c, m));
            if c.c_enum {
                family.push_str(&assert);
            } else {
                let _ = write!(family, "#ifdef {0}\n{assert}#endif\n", m.c_name);
            }
        }
        if !family.is_empty() {
            let _ = write!(out, "\n/* {} */\n{family}", t.name);
        }
    }
    Ok(out)
}

/// Flags read best in hex, enums in decimal; every literal must be valid C for its value.
fn c_literal(c: &Constants, m: &Constant) -> String {
    let v = m.value;
    if v == i128::from(i64::MIN) {
        "(-0x7fffffffffffffff - 1)".to_string()
    } else if v > i128::from(i64::MAX) || (c.kind == ConstKind::Flags && v >= 0) {
        format!("{v:#x}")
    } else {
        v.to_string()
    }
}

