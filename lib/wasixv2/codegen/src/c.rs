//! [`Model`] -> C glue for libc2 (the musl fork).
//!
//! musl's `__syscallN(nr, ...)` macros token-paste the syscall *number* into `__wx2_nr_<nr>(...)`,
//! an "arm" that casts musl's `long` argument slots to the typed `wasixv2` import's parameters.
//! A 64-bit param occupies two slots (musl splits it) and the arm reassembles it into one i64,
//! unless it is `@c-one-slot`: musl passes it in one `long` slot and the arm sign-extends it.
//! The non-generated half of this lives in libc2's `arch/wasm32/syscall_arch.h`.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write as _;

use anyhow::{Result, bail};

use crate::ir::{
    ConstKind, Constant, Constants, Function, Model, Param, Prim, SplitOrder, Target, TyRef,
    TypeDef, TypeKind, names,
};

/// Import module of the Linux syscalls (functions with `@nr`) and the extensions.
pub const SYSCALL_MODULE: &str = "wasixv2";

/// First line of every generated file except `bits/syscall.h.in`.
pub const HEADER: &str = "/* @generated by wasixv2-codegen. DO NOT EDIT. */\n";

pub const SYSCALL_NUMBERS_PATH: &str = "arch/wasm32/bits/syscall.h.in";
pub const SYSCALLS_HEADER_PATH: &str = "arch/wasm32/wasix2_syscalls.h";
pub const DYN_PATH: &str = "src/internal/wasm32/wasix2_dyn.c";
pub const ASSERTS_PATH: &str = "src/internal/wasm32/wasix2_asserts.c";

/// musl passes at most six argument slots.
const MAX_SLOTS: usize = 6;

/// `__NR_<alias>` lines musl code needs, as `(alias, target)`; emitted when the target exists.
const NR_ALIASES: &[(&str, &str)] = &[("futex", "futex_time64")];

