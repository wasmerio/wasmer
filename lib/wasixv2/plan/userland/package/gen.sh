#!/usr/bin/env bash
# Generates package/wasmer.toml from out/bin and copies the modules into
# package/modules/, then builds the webc (v3) with `wasmer package build`.
# Local only: never published. WASMER selects the CLI. Shell scripts in out/bin
# (gzip's gunzip, zcat, ...) are not modules and are left out of the package.
set -euo pipefail
P=$(cd "$(dirname "$0")" && pwd)
OUT=$P/../out/bin
W=${WASMER:-wasmer}
rm -rf "$P/modules" && mkdir -p "$P/modules"
# is_wasm <file>: a wasm module (or a symlink to one), by its magic number.
is_wasm() { [ "$(head -c 4 "$1" | od -An -tx1 | tr -d ' ')" = 0061736d ]; }
{
  cat <<'H'
# Generated by gen.sh; do not edit.
[package]
name = "wasix-org/userland-v2"
version = "0.1.0"
description = "GNU bash, coreutils, grep, sed, gawk, findutils, diffutils, which, gzip, tar, cpio, bzip2, Info-ZIP unzip, util-linux, procps-ng and psmisc programs for WASIX v2 (asyncify builds)"
license = "GPL-3.0-or-later AND GPL-2.0-or-later AND LGPL-2.1-or-later AND bzip2-1.0.6 AND Info-ZIP"
entrypoint = "bash"
H
  for f in "$OUT"/*; do
    [ -L "$f" ] && continue
    is_wasm "$f" || continue
    m=$(basename "$f")
    cp "$f" "$P/modules/$m.wasm"
    printf '\n[[module]]\nname = "%s"\nsource = "modules/%s.wasm"\nabi = "wasi"\n' "$m" "$m"
  done
  for f in "$OUT"/*; do
    is_wasm "$f" || continue
    c=$(basename "$f")
    m=$c
    [ -L "$f" ] && m=$(readlink "$f")
    printf '\n[[command]]\nname = "%s"\nmodule = "%s"\nrunner = "wasi"\n' "$c" "$m"
  done
} > "$P/wasmer.toml"
"$W" package build "$P" -o "$P/userland-v2-0.1.0.webc"
ls -la "$P/userland-v2-0.1.0.webc"
